@pytest.mark.parametrize('model', ['garch', 'gjr'])
def test_simulate_unconditional_vol(model):
    true = dict(omega=0.05, alpha=0.06, gamma=0.10, beta=0.86)
    y = _simulate(model, 'normal', true, T=3000, seed=0)
    res = fit_volatility(y, model=model, dist='normal')

    omega, alpha = res.params['omega'], res.params['alpha']
    beta = res.params['beta']
    gamma = res.params.get('gamma', 0.0)
    uncond_std = np.sqrt(omega / (1.0 - alpha - beta - 0.5 * gamma))

    sim = res.simulate(30000, seed=0)
    assert sim.shape == (30000,)
    assert np.all(np.isfinite(sim))
    assert abs(np.std(sim) - uncond_std) / uncond_std < 0.10


def test_simulate_is_seeded():
    y = _simulate('egarch', 'normal',
                  dict(omega=-0.1, alpha=0.15, gamma=-0.10, beta=0.95),
                  T=1000, seed=0)
    res = fit_volatility(y, model='egarch', dist='normal')
    a = res.simulate(500, seed=42)
    b = res.simulate(500, seed=42)
    c = res.simulate(500, seed=7)

    assert np.array_equal(a, b)
    assert not np.array_equal(a, c)


