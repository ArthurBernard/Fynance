#!/usr/bin/env python3
# coding: utf-8

""" Tests for the maximum-likelihood GARCH-family volatility driver. """

# Third-party packages
import numpy as np
import pytest

# Local packages
from fynance.estimator import VolatilityResult, fit_volatility
from fynance.models.econometric_models import (
    _mean_abs_standardized_t,
    loglik_garch,
)

# --------------------------------------------------------------------------- #
#                              Simulation helpers                             #
# --------------------------------------------------------------------------- #


def _draw(rng, dist, nu, T):
    """ Unit-variance innovation draws matching the kernel conventions. """
    if dist == 'normal':
        return rng.standard_normal(T)

    return rng.standard_t(nu, T) * np.sqrt((nu - 2.0) / nu)


def _simulate(model, dist, params, T, seed):
    """ Simulate a return path from the kernels' own recursion conventions. """
    rng = np.random.default_rng(seed)
    nu = params.get('nu', 8.0)
    z = _draw(rng, dist, nu, T)
    omega, alpha, beta = params['omega'], params['alpha'], params['beta']
    gamma = params.get('gamma', 0.0)
    y = np.empty(T)

    if model in ('garch', 'gjr'):
        var = omega  # sigma_0^2 = omega.
        y[0] = np.sqrt(var) * z[0]
        for t in range(1, T):
            ind = 1.0 if y[t - 1] < 0.0 else 0.0
            var = omega + (alpha + gamma * ind) * y[t - 1] ** 2 + beta * var
            y[t] = np.sqrt(var) * z[t]

    else:  # egarch.
        maz = _mean_abs_standardized_t(nu) if dist == 't' else np.sqrt(2 / np.pi)
        log_var = omega
        y[0] = np.exp(0.5 * log_var) * z[0]
        for t in range(1, T):
            log_var = (omega + beta * log_var
                       + alpha * (abs(z[t - 1]) - maz) + gamma * z[t - 1])
            y[t] = np.exp(0.5 * log_var) * z[t]

    return y


# (model, dist, true params, seed) — seeds chosen for robust <15% recovery.
RECOVERY_CASES = [
    ('garch', 'normal', dict(omega=0.05, alpha=0.10, beta=0.85), 2),
    ('garch', 't', dict(omega=0.05, alpha=0.10, beta=0.85, nu=6.0), 2),
    ('gjr', 'normal', dict(omega=0.05, alpha=0.06, gamma=0.12, beta=0.86), 4),
    ('gjr', 't',
     dict(omega=0.05, alpha=0.06, gamma=0.12, beta=0.86, nu=6.0), 3),
    ('egarch', 'normal',
     dict(omega=-0.1, alpha=0.15, gamma=-0.10, beta=0.95), 0),
    ('egarch', 't',
     dict(omega=-0.1, alpha=0.15, gamma=-0.10, beta=0.95, nu=6.0), 3),
]


# --------------------------------------------------------------------------- #
#                            Parameter recovery                               #
# --------------------------------------------------------------------------- #


@pytest.mark.parametrize('model,dist,true,seed', RECOVERY_CASES)
def test_parameter_recovery(model, dist, true, seed):
    # On a long simulated series the MLE recovers every parameter within 15%.
    y = _simulate(model, dist, true, T=5000, seed=seed)
    res = fit_volatility(y, model=model, dist=dist)

    assert isinstance(res, VolatilityResult)
    assert res.model == model and res.dist == dist and res.n_obs == 5000
    assert set(res.params) == set(true)

    for name, truth in true.items():
        rel = abs(res.params[name] - truth) / abs(truth)
        assert rel <= 0.15, f"{model}-{dist} {name}: {res.params[name]} vs {truth}"


@pytest.mark.parametrize('model,dist,true,seed', RECOVERY_CASES)
def test_loglik_fit_at_least_truth(model, dist, true, seed):
    # The maximised log-likelihood is never below the truth's log-likelihood.
    y = _simulate(model, dist, true, T=5000, seed=seed)
    res = fit_volatility(y, model=model, dist=dist)

    names = ['omega', 'alpha', 'beta'] if model == 'garch' else \
        ['omega', 'alpha', 'gamma', 'beta']
    if dist == 't':
        names = names + ['nu']
    truth_vec = np.array([true[n] for n in names])
    ll_truth = loglik_garch(truth_vec, y - np.mean(y), model=model, dist=dist)

    assert res.loglik >= ll_truth - 1e-6


