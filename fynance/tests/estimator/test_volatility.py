@pytest.mark.parametrize('model', ['garch', 'gjr'])
def test_forecast_h1_equals_filter_next_step(model):
    # The one-step variance forecast is exactly the filter's next-step value.
    true = dict(omega=0.05, alpha=0.06, gamma=0.10, beta=0.86)
    y = _simulate(model, 'normal', true, T=3000, seed=0)
    res = fit_volatility(y, model=model, dist='normal')

    omega, alpha = res.params['omega'], res.params['alpha']
    beta = res.params['beta']
    gamma = res.params.get('gamma', 0.0)
    eps_last = res.std_residuals[-1] * res.conditional_vol[-1]
    ind = 1.0 if eps_last < 0.0 else 0.0
    expected = (omega + (alpha + gamma * ind) * eps_last ** 2
                + beta * res.conditional_vol[-1] ** 2)

    assert res.forecast(1)[0] == expected


@pytest.mark.parametrize('model', ['garch', 'gjr'])
def test_forecast_converges_to_unconditional_variance(model):
    true = dict(omega=0.05, alpha=0.06, gamma=0.10, beta=0.86)
    y = _simulate(model, 'normal', true, T=3000, seed=0)
    res = fit_volatility(y, model=model, dist='normal')

    omega, alpha = res.params['omega'], res.params['alpha']
    beta = res.params['beta']
    gamma = res.params.get('gamma', 0.0)
    uncond = omega / (1.0 - alpha - beta - 0.5 * gamma)

    fc = res.forecast(500)
    assert fc.shape == (500,)
    assert np.all(fc > 0.0)
    assert abs(fc[-1] - uncond) / uncond < 0.10


def test_egarch_forecast_is_positive_and_seeded():
    true = dict(omega=-0.1, alpha=0.15, gamma=-0.10, beta=0.95)
    y = _simulate('egarch', 'normal', true, T=3000, seed=0)
    res = fit_volatility(y, model='egarch', dist='normal')

    fc = res.forecast(10, n_sims=2000, seed=0)
    assert fc.shape == (10,)
    assert np.all(fc > 0.0)
    # Monte-Carlo is seeded: identical seed reproduces the path exactly.
    assert np.array_equal(fc, res.forecast(10, n_sims=2000, seed=0))


def test_forecast_bad_horizon_raises():
    y = _simulate('garch', 'normal', dict(omega=0.05, alpha=0.1, beta=0.85),
                  T=500, seed=0)
    res = fit_volatility(y, model='garch', dist='normal')
    with pytest.raises(ValueError, match='h must be'):
        res.forecast(0)


