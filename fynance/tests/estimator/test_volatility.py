def test_x0_override_is_used():
    # An explicit x0 must be accepted and still yield a valid fit.
    y = _simulate('garch', 'normal', dict(omega=0.05, alpha=0.10, beta=0.85),
                  T=2000, seed=0)
    res = fit_volatility(y, model='garch', dist='normal',
                         x0=[0.1, 0.05, 0.9])
    assert np.isfinite(res.loglik)
    assert set(res.params) == {'omega', 'alpha', 'beta'}


def test_conditional_vol_and_residuals_consistent():
    y = _simulate('garch', 'normal', dict(omega=0.05, alpha=0.10, beta=0.85),
                  T=1000, seed=0)
    res = fit_volatility(y, model='garch', dist='normal')

    assert res.conditional_vol.shape == (1000,)
    assert res.std_residuals.shape == (1000,)
    assert np.all(res.conditional_vol > 0.0)
    # std_residuals == (demeaned y) / conditional_vol.
    yd = y - np.mean(y)
    assert np.allclose(res.std_residuals, yd / res.conditional_vol)


