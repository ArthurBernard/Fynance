def test_aic_bic_formulas_exact():
    y = _simulate('garch', 'normal', dict(omega=0.05, alpha=0.10, beta=0.85),
                  T=2000, seed=1)
    res = fit_volatility(y, model='garch', dist='normal')
    k, n = len(res.params), res.n_obs

    assert np.isclose(res.aic, 2 * k - 2 * res.loglik)
    assert np.isclose(res.bic, k * np.log(n) - 2 * res.loglik)


def test_aic_ranking_prefers_true_family():
    # Data generated by GJR-t: among the six model x dist fits, GJR-t wins AIC.
    true = dict(omega=0.05, alpha=0.06, gamma=0.12, beta=0.86, nu=6.0)
    y = _simulate('gjr', 't', true, T=5000, seed=3)

    aic = {}
    for model in ('garch', 'gjr', 'egarch'):
        for dist in ('normal', 't'):
            aic[(model, dist)] = fit_volatility(y, model=model, dist=dist).aic

    assert min(aic, key=aic.get) == ('gjr', 't')


