def test_ma_parity():
    assert np.allclose(_ma(Y, THETA, 0.5, 2), GOLD_MA, atol=1e-10)


def test_arma_parity():
    assert np.allclose(_arma(Y, PHI, THETA, 0.5, 2, 2), GOLD_ARMA, atol=1e-10)


def test_arma_garch_parity():
    u, h = _arma_garch(Y, PHI, THETA, ALPHA, BETA, 0.5, 0.1, 2, 2, 1, 1)
